#!/usr/bin/env python3
"""Generates the C++ source with the data that tona carries: the model catalog (toolchain/models.toml) and the
expert profiles (toolchain/profiles/*.bin).

Embedded in the binary, both are signed together with the installer: a release installation takes the model revisions,
sizes and SHA-256 sums from the signed program, never from a file on the machine or from a server. The output is a
pure function of the inputs (no date, no paths), so the release build stays reproducible.

  tools/gen_installer_data.py OUT.cpp [--models FILE] [--profiles DIR]
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
KEYS = ("title", "kind", "license", "quality", "repo", "revision", "mtp")
SAFE_NAME = re.compile(r"[A-Za-z0-9_-][A-Za-z0-9._-]*")
FILE_KEYS = ("repo", "revision", "save_as")  # optional per file: a byte-equal file pinned in another repository


def lit(s: str) -> str:
    """C++ string literal; the inputs are ASCII, anything else is an error rather than a silent mangling."""
    s.encode("ascii")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def entry(model_id: str, m: dict) -> str:
    files = ",\n".join(
        f"        {{{lit(f['path'])}, {int(f['size'])}ULL, {lit(f['sha256'])}, "
        + ", ".join(lit(f.get(k, "")) for k in FILE_KEYS)
        + "}"
        for f in m["files"]
    )
    fields = ", ".join(lit(m.get(k, "")) for k in KEYS)
    tested = "true" if m.get("tested", False) else "false"
    return f"    {{{lit(model_id)}, {fields}, {tested}, {{\n{files},\n    }}}}"


def profile(name: str, data: bytes) -> str:
    rows = [", ".join(str(b) for b in data[i : i + 24]) for i in range(0, len(data), 24)]
    body = ",\n".join("        " + r for r in rows)
    return f"    {{{lit(name)}, {{\n{body},\n    }}}}"


def generate(models: dict, profiles: dict[str, bytes]) -> str:
    out = [
        "// Generated by tools/gen_installer_data.py from toolchain/models.toml and toolchain/profiles/. Do not edit.",
        '#include "core/catalog.h"',
        "",
        "namespace tona::install {",
        "",
        "const std::vector<CatalogEntry>& embedded_catalog() {",
        "    static const std::vector<CatalogEntry> catalog = {",
    ]
    out.append(",\n".join(entry(k, v) for k, v in models.items()) + ",")
    out += [
        "    };",
        "    return catalog;",
        "}",
        "",
        "const std::vector<ProfileBlob>& embedded_profiles() {",
        "    static const std::vector<ProfileBlob> profiles = {",
    ]
    out.append(",\n".join(profile(k, v) for k, v in sorted(profiles.items())) + ("," if profiles else ""))
    out += ["    };", "    return profiles;", "}", "", "}  // namespace tona::install", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--models", default=str(REPO / "toolchain" / "models.toml"))
    ap.add_argument("--profiles", default=str(REPO / "toolchain" / "profiles"))
    a = ap.parse_args()
    models = tomllib.loads(Path(a.models).read_text())
    for k, m in models.items():
        if not m.get("files") or any(not {"path", "size", "sha256"} <= f.keys() for f in m["files"]):
            sys.exit(f"{k}: every entry needs files with path, size and sha256")
        if any(f.keys() - {"path", "size", "sha256", *FILE_KEYS} for f in m["files"]):
            sys.exit(f"{k}: unknown file key (known: path, size, sha256, {', '.join(FILE_KEYS)})")
        # save_as becomes a path on the user's disk: a plain file name only, never a directory part or ".."
        if any(not SAFE_NAME.fullmatch(f.get("save_as", "x")) for f in m["files"]):
            sys.exit(f"{k}: save_as must be a plain file name ([A-Za-z0-9_-][A-Za-z0-9._-]*)")
    profiles = {p.stem: p.read_bytes() for p in Path(a.profiles).glob("*.bin")}
    Path(a.out).write_text(generate(models, profiles))
    return 0


if __name__ == "__main__":
    sys.exit(main())
