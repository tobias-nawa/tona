#!/usr/bin/env python3
"""Generates engine/model/unicode_case_tables.h: the code points of \\p{Lu}+\\p{Lt} and of \\p{Ll} as ranges.

The Tekken pre-tokenizer regex (model/pretok_pixtral.cpp) needs the two classes apart. The data is the Unicode version
of the Python that runs this script (printed into the header).

Usage: tools/gen_case_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "engine/model/unicode_case_tables.h"


def ranges(cats: tuple[str, ...]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for c in range(0x110000):
        if unicodedata.category(chr(c)) in cats:
            if out and out[-1][1] == c - 1:
                out[-1] = (out[-1][0], c)
            else:
                out.append((c, c))
    return out


def emit(name: str, rs: list[tuple[int, int]]) -> str:
    items = [f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs]
    rows = ["    " + " ".join(items[i : i + 6]) for i in range(0, len(items), 6)]
    return f"inline constexpr CaseRange {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main() -> int:
    head = (
        f"// Code point ranges of \\p{{Lu}}+\\p{{Lt}} and of \\p{{Ll}}, Unicode {unicodedata.unidata_version}.\n"
        "// Generated by tools/gen_case_tables.py; do not edit, regenerate instead.\n"
        "#pragma once\n\n#include <cstdint>\n\nnamespace tona::tables {\n\n"
        "struct CaseRange {\n    uint32_t first, last;  // both included\n};\n\n"
    )
    body = emit("unicode_upper_title", ranges(("Lu", "Lt"))) + "\n" + emit("unicode_lower", ranges(("Ll",)))
    OUT.write_text(head + body + "\n}  // namespace tona::tables\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
