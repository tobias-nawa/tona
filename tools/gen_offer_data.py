#!/usr/bin/env python3
"""Generates the C++ source with the offer data (data/modeldb/offer.json) for engine/offer/offer.h.

The installer and the client (tona) link the same library, so both show the same tasks, recommendations, language
verdicts and rates, each with its basis word and source. The size on disk of a model is not stored in the offer file:
it is the sum of the file sizes pinned in toolchain/models.toml, so the catalog stays the one source for it.
The output is a pure function of the two inputs (no date, no paths), so the release build stays reproducible.

  tools/gen_offer_data.py OUT.cpp [--offer FILE] [--models FILE]
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BASIS = {
    "measured": "Measured",
    "provisional": "Provisional",
    "vendor": "Vendor",
    "independent": "Independent",
    "none": "None",
}
LEVEL = {"strong": "Strong", "weak": "Weak", "open": "Open"}


def lit(s: str) -> str:
    """C++ string literal of UTF-8 text: every non-ASCII byte as a 3-digit octal escape, so the source stays ASCII."""
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def text(t: str | None) -> str:
    return lit(t or "")


def flag(b: bool) -> str:
    return "true" if b else "false"


def num(v: float | int | None) -> str:
    return "std::nullopt" if v is None else f"std::optional<double>{{{float(v)!r}}}"


def remark(r: dict) -> str:
    return f"{{{text(r['text'])}, Basis::{BASIS[r['basis']]}, {lit(r['source'])}, {text(r.get('brief'))}}}"


def rate(r: dict) -> str:
    return (
        f"{{{int(r['context_tokens'])}, {num(r.get('decode_tps'))}, {num(r.get('prefill_tps'))}, "
        f"Basis::{BASIS[r['basis']]}, {text(r['note'])}, {lit(r['source'])}}}"
    )


def verdict(lang: str, v: dict) -> str:
    return (
        f"{{{lit(lang)}, Level::{LEVEL[v['level']]}, Basis::{BASIS[v['basis']]}, "
        f"{text(v['detail'])}, {lit(v['source'])}}}"
    )


def lst(items: list[str]) -> str:
    return "{" + ",\n          ".join(items) + "}" if items else "{}"


def card(model_id: str, c: dict, size: int, languages: list[str]) -> str:
    lic = c["license"]
    return (
        f"        {{{lit(model_id)}, {lit(c['name'])}, {lit(c['modeldb'])}, {size}ULL,\n"
        f"         {lst([verdict(k, c['languages'][k]) for k in languages])},\n"
        f"         {lst([remark(r) for r in c['strengths']])},\n"
        f"         {lst([remark(r) for r in c['weaknesses']])},\n"
        f"         {lst([rate(r) for r in c['rates']])},\n"
        f"         {{{text(lic['text'])}, {flag(lic['verified'])}, {lit(lic['source'])}}}}}"
    )


def sizes(models: dict, ids: list[str]) -> dict[str, int]:
    out = {}
    for model_id in ids:
        if model_id not in models:
            sys.exit(f"{model_id}: not in toolchain/models.toml")
        out[model_id] = sum(int(f["size"]) for f in models[model_id]["files"])
    return out


def task(t: dict) -> str:
    return (
        f"        {{{lit(t['id'])}, {text(t['label'])}, {text(t['help'])}, {flag(t['status'] == 'available')}, "
        f"{text(t.get('coming_note'))}}}"
    )


def offer_row(o: dict) -> str:
    return (
        f"        {{{lit(o['task'])}, {lit(o['hw_class'])}, {lit(o['recommended'])}, {lit(o.get('alternative', ''))}, "
        f"{text(o['reason'])}, {lit(o['source'])}}}"
    )


def hw_class(c: dict) -> str:
    return f"        {{{lit(c['id'])}, {text(c['label'])}, {lit(c['doc'])}, {flag(c['measured'])}}}"


def function(ret: str, name: str, rows: list[str]) -> str:
    body = ",\n".join(rows)
    head = f"const std::vector<{ret}>& {name}() {{\n    static const std::vector<{ret}> v = {{\n"
    return head + body + ",\n    };\n    return v;\n}\n"


def generate(offer: dict, models: dict) -> str:
    languages = [lang["id"] for lang in offer["languages"]]
    size = sizes(models, list(offer["models"]))
    parts = [
        "// Generated by tools/gen_offer_data.py from data/modeldb/offer.json and toolchain/models.toml. Do not edit.",
        '#include "offer/offer.h"',
        "",
        "namespace tona::offer {",
        "",
        function("HwClass", "hw_classes", [hw_class(c) for c in offer["hw_classes"]]),
        function(
            "Language", "languages", [f"        {{{lit(x['id'])}, {lit(x['label'])}}}" for x in offer["languages"]]
        ),
        function("Task", "tasks", [task(t) for t in offer["tasks"]]),
        function("Offer", "offers", [offer_row(o) for o in offer["offers"]]),
        function("ModelCard", "model_cards", [card(k, v, size[k], languages) for k, v in offer["models"].items()]),
        "}  // namespace tona::offer",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--offer", default=str(REPO / "data" / "modeldb" / "offer.json"))
    ap.add_argument("--models", default=str(REPO / "toolchain" / "models.toml"))
    a = ap.parse_args()
    offer = json.loads(Path(a.offer).read_text())
    models = tomllib.loads(Path(a.models).read_text())
    Path(a.out).write_text(generate(offer, models))
    return 0


if __name__ == "__main__":
    sys.exit(main())
