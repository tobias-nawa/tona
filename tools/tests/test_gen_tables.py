import re
from pathlib import Path

import gen_tables
import pytest
from conftest import ROOT

TABLES = [
    ("uint8_t", "kmask_iq2xs", 8),
    ("uint8_t", "ksigns_iq2xs", 128),
    ("uint64_t", "iq2xxs_grid", 256),
    ("uint64_t", "iq2s_grid", 1024),
    ("uint32_t", "iq3xxs_grid", 256),
    ("uint32_t", "iq3s_grid", 512),
    ("int8_t", "kvalues_iq4nl", 16),
]


def fake_llama(root: Path) -> Path:
    """Source files with the structure gen_tables.py reads and small invented contents."""
    common = ["// header"]
    for ctype, name, n in TABLES:
        values = ", ".join(str(i % 100) for i in range(n))
        common += [f"GGML_TABLE_BEGIN({ctype}, {name}, {n})", f"    {values}, // comment 99", "GGML_TABLE_END()"]
    (root / "ggml/src").mkdir(parents=True)
    (root / "ggml/src/ggml-common.h").write_text("\n".join(common))
    (root / "src").mkdir()
    (root / "src/unicode-data.cpp").write_text(
        "static const std::vector<std::pair<uint32_t, uint16_t>> unicode_ranges_flags = {  // start, flags\n"
        "{0x000000, 0x0001}, {0x000030, 0x0102}, {0x110000, 0x0001},\n};\n"
        "static const std::unordered_set<uint32_t> unicode_set_whitespace = {0x000009, 0x000020, 0x0000A0};\n"
    )
    return root


def test_numbers_ignores_comments_and_reads_hex_and_negative():
    assert gen_tables.numbers("-1, 0x1F, 12 // 99 0x7\n, -0x2") == ["-1", "0x1F", "12", "-0x2"]


def test_quant_tables_have_declared_sizes(tmp_path):
    text = gen_tables.quant(fake_llama(tmp_path))
    for ctype, name, n in TABLES:
        body = re.search(rf"inline constexpr {ctype} {name}\[{n}\] = \{{(.*?)\}};", text, re.S)
        assert body and len(re.findall(r"-?\d+", body.group(1))) == n
    assert text.startswith("// Lookup tables of the IQ formats")
    assert "Generated by tools/gen_tables.py" in text and text.endswith("}  // namespace tona::tables\n")


def test_quant_rejects_a_table_of_the_wrong_length(tmp_path):
    src = fake_llama(tmp_path)
    path = src / "ggml/src/ggml-common.h"
    path.write_text(
        path.read_text().replace(
            "GGML_TABLE_BEGIN(int8_t, kvalues_iq4nl, 16)\n", "GGML_TABLE_BEGIN(int8_t, kvalues_iq4nl, 16)\n 1,"
        )
    )
    with pytest.raises(AssertionError):
        gen_tables.quant(src)


def test_unicode_tables(tmp_path):
    text = gen_tables.unicode(fake_llama(tmp_path))
    assert "unicode_range_start[3] = {" in text and "0x0, 0x30, 0x110000" in text.replace("0x000000", "0x0").replace(
        "0x000030", "0x30"
    )
    assert "unicode_range_flags[3] = {" in text and "0x1, 0x2, 0x1" in text
    assert "unicode_whitespace[3] = {" in text and "0x000009, 0x000020, 0x0000A0" in text


def test_unicode_checks_the_range_bounds(tmp_path):
    src = fake_llama(tmp_path)
    path = src / "src/unicode-data.cpp"
    path.write_text(path.read_text().replace("{0x110000, 0x0001}", "{0x100000, 0x0001}"))
    with pytest.raises(AssertionError):
        gen_tables.unicode(src)


def test_main_writes_both_headers(tmp_path, monkeypatch, capsys):
    out = tmp_path / "engine/model"
    out.mkdir(parents=True)
    monkeypatch.setattr(gen_tables, "ROOT", tmp_path)
    monkeypatch.setattr("sys.argv", ["gen_tables.py", str(fake_llama(tmp_path / "llama"))])
    assert gen_tables.main() == 0
    assert (out / "quant_tables.h").read_text().startswith("// Lookup tables")
    assert (out / "unicode_tables.h").is_file()
    assert capsys.readouterr().out.split() == ["engine/model/quant_tables.h", "engine/model/unicode_tables.h"]


def test_committed_headers_have_the_sizes_they_declare():
    """Catches a hand edit of a generated file; the full comparison with llama.cpp needs its sources."""
    for name in ("quant_tables.h", "unicode_tables.h"):
        text = (ROOT / "engine/model" / name).read_text()
        assert "Generated by tools/gen_tables.py" in text
        arrays = re.findall(r"inline constexpr \w+ (\w+)\[(\d+)\] = \{(.*?)\};", text, re.S)
        assert arrays
        for array_name, size, body in arrays:
            assert len(re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)) == int(size), array_name
