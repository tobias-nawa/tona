#!/usr/bin/env bash
# Usage: scripts/build-fresh.sh BUILD_DIR BINARY...
# Exit 0 if every BINARY in BUILD_DIR is newer than everything it is built from, else exit 2 with the reason. The
# golden checks call it: a reference recorded or compared with a stale binary says nothing about the sources (the
# mini references were recorded with a binary from before IndexCache became the default and did not reproduce for days).
# "Built from" is what ninja knows: `ninja -t inputs BINARY` (sources, objects, libraries, transitively) and `ninja -t
# deps` of those objects (the headers the compiler read). A file the binary does not depend on (tests, the updater,
# AGENTS.md) never makes it stale, so a rebuild always fixes a refusal. CMakeLists.txt and *.cmake of the source
# directory count too (ninja lists them for the manifest only). Not checked: /usr and the ROCm toolchain (a compiler
# update needs a clean build anyway), and nothing is built or regenerated by this script.
# Why not `ninja -n`: it stops at "Re-running CMake..." (also on a build that is up to date) and then reports nothing
# about the sources. Why the source directory of the cache and not of this checkout: gpu-status.sh checks a build of
# another worktree with the scripts of this one. A touched file with unchanged content counts as stale; one
# ccache-backed `just build` fixes that. Takes about 0.5 s for two binaries.
set -euo pipefail
build=${1:?build directory}
shift
[[ $# -gt 0 ]] || { echo "usage: $0 BUILD_DIR BINARY..." >&2; exit 2; }
cache=$build/CMakeCache.txt
[[ -f $cache ]] || { echo "$build is not a CMake build directory (no CMakeCache.txt); build the engine first (just build)" >&2; exit 2; }
home=$(sed -n 's/^CMAKE_HOME_DIRECTORY:INTERNAL=//p' "$cache")
[[ -d $home ]] || { echo "the sources of $build ($home) are gone; build the engine again in a fresh directory" >&2; exit 2; }
build=$(cd "$build" && pwd)

stale() { # BINARY FILE
    echo "$build/$1 is older than what it is built from ($2 is newer): the build is stale, a golden check on it proves nothing." >&2
    echo "Rebuild first: just build_dir=$build build" >&2
    exit 2
}

for bin in "$@"; do
    [[ -x $build/$bin ]] || { echo "$build/$bin is missing; build the engine first (just build)" >&2; exit 2; }
    inputs=$(ninja -C "$build" -t inputs "$bin") || { echo "ninja does not know $bin in $build" >&2; exit 2; }
    objects=()
    while IFS= read -r f; do
        # ninja before 1.12 also lists the phony order-only targets of CMake (a file that never exists)
        if [[ $f == . || $f == /usr/* || $f == */rocm-10.1/* || $f == cmake_object_order_depends_* ]]; then continue; fi
        if [[ $f != /* ]]; then f=$build/$f; fi
        if [[ ! -e $f ]]; then stale "$bin" "$f (missing)"; fi
        if [[ $f -nt $build/$bin ]]; then stale "$bin" "$f"; fi
        if [[ $f == *.o ]]; then objects+=("${f#"$build"/}"); fi
    done <<<"$inputs"
    [[ ${#objects[@]} -gt 0 ]] || { echo "ninja lists no object files for $bin in $build" >&2; exit 2; }
    # Header dependencies are recorded per object after its first build; an object without them was never built
    while IFS= read -r f; do
        f=${f#"${f%%[![:space:]]*}"}
        if [[ $f == /usr/* || $f == */rocm-10.1/* ]]; then continue; fi
        if [[ $f -nt $build/$bin ]]; then stale "$bin" "$f"; fi
    done < <(ninja -C "$build" -t deps "${objects[@]}" | grep '^ ' || true)
    newer=$(find "$home" \( -name CMakeLists.txt -o -name '*.cmake' \) -newer "$build/$bin" -not -path '*/.git/*' -print -quit)
    [[ -z $newer ]] || stale "$bin" "$newer"
done
